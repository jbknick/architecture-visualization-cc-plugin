// Builds packages/core/src/describe/wordlist.data.ts: a Bloom filter over an English word list, used by the description
// validator (spec section 8) to decide whether a token is an ordinary word. Usage:
//   pnpm exec tsx scripts/build-wordlist.ts /usr/share/dict/words
// Provenance: /usr/share/dict/words on macOS and FreeBSD is Webster's Second International (web2), 234,936 entries.
// /usr/share/dict/README says "The 1934 copyright has lapsed", so the list is public domain. Only the words are used
// (a set of strings), not any definitions. Rules: lowercase alphabetic words of 4 to 20 letters (proper nouns are
// lower-cased); shorter words come from the hand list in wordlist.ts, because web2 holds many obscure two- and
// three-letter entries that would double as host names. Output is deterministic: same input, same bytes.

import { readFileSync, writeFileSync } from "node:fs";
import { bloomHashes, bloomIndex } from "../packages/core/src/describe/bloom.js";

const FP_BITS_PER_WORD = 15; // with k = 10 this gives about 0.07% false positives (measured in wordlist.test.ts)
const K = 10;

const path = process.argv[2];
if (path === undefined) {
  console.error("usage: tsx scripts/build-wordlist.ts <words-file>");
  process.exit(1);
}
const words = [
  ...new Set(
    readFileSync(path, "latin1")
      .split("\n")
      .map((w) => w.trim().toLowerCase())
      .filter((w) => /^[a-z]{4,20}$/.test(w)),
  ),
].sort();
const m = Math.ceil(words.length * FP_BITS_PER_WORD);
const bits = new Uint8Array(Math.ceil(m / 8));
for (const w of words) {
  const [h1, h2] = bloomHashes(w);
  for (let i = 0; i < K; i++) {
    const idx = bloomIndex(h1, h2, i, m);
    bits[idx >> 3] = (bits[idx >> 3] as number) | (1 << (idx & 7));
  }
}
const b64 = Buffer.from(bits).toString("base64");
const out = `// GENERATED by scripts/build-wordlist.ts. Do not edit. Bloom filter over ${words.length} English words
// (Webster's Second International, 1934, copyright lapsed; see scripts/build-wordlist.ts).
export const WORD_COUNT = ${words.length};
export const WORD_BITS = ${m};
export const WORD_HASHES = ${K};
export const WORD_BLOOM_BASE64 =
  "${b64}";
`;
writeFileSync(new URL("../packages/core/src/describe/wordlist.data.ts", import.meta.url), out);
console.log(`${words.length} words, ${m} bits, ${b64.length} base64 chars`);
