import { describe, expect, it } from "vitest";
import { hashStreams } from "../../hash/index.js";
import { parseWithPack } from "../engine/parse.js";
import { embeddingTextWithPack, streamsWithPack } from "../engine/streams.js";
import { parseGroupMembers, parseManifestDeps, parseManifestName } from "../engine/workspace.js";
import { goPack } from "./index.js";

type Range = { start: number; end: number };
const parseGoSource = (repo: string, path: string, src: string) => parseWithPack(goPack, repo, path, src);
const goStreams = (src: string, range: Range, _path: string) => streamsWithPack(goPack, src, range);
const goEmbeddingText = (src: string, range: Range, _path: string) =>
  embeddingTextWithPack(goPack, src, range);
const parseModulePath = (text: string) => parseManifestName(goPack, text);
const parseRequires = (text: string) => parseManifestDeps(goPack, text);
const parseGoWorkUses = (text: string) => parseGroupMembers(goPack, text);

const parse = (src: string, path = "pkg/a.go") => parseGoSource("r", path, src);
const byName = (src: string) => new Map(parse(src).symbols.map((s) => [s.name, s]));

describe("go kind mapping", () => {
  const src = `package a

type S struct{ n int }
type I interface{ M() }
type D []int
type A = S
type G[T any] struct{ v T }

const C = 1
var V = 2

func F() {}
func (s *S) M() {}
`;
  it("maps declarations to the neutral kinds", () => {
    const m = byName(src);
    expect(m.get("F")?.kind).toBe("function");
    expect(m.get("S.M")?.kind).toBe("method");
    expect(m.get("S")?.kind).toBe("class");
    expect(m.get("G")?.kind).toBe("class");
    expect(m.get("I")?.kind).toBe("interface");
    expect(m.get("D")?.kind).toBe("type");
    expect(m.get("A")?.kind).toBe("type");
    expect(m.get("C")?.kind).toBe("const");
    expect(m.get("V")?.kind).toBe("const");
  });

  it("flags exported names by the case of the first letter", () => {
    const m = byName("package a\nfunc Pub() {}\nfunc priv() {}\nfunc (s S) Get() {}\nfunc (s S) get() {}\n");
    expect(m.get("Pub")?.exported).toBe(true);
    expect(m.get("priv")?.exported).toBe(false);
    expect(m.get("S.Get")?.exported).toBe(true);
    expect(m.get("S.get")?.exported).toBe(false);
  });
});

describe("go receivers", () => {
  it("uses the receiver base type: *T, T[K], *T[K], (T) and unnamed receivers", () => {
    const m = byName(`package a
func (t *T) A() {}
func (t T) B() {}
func (t T[K]) C() {}
func (t *T[K, V]) D() {}
func (T) E() {}
func (*T) F() {}
`);
    expect([...m.keys()].sort()).toEqual(["T.A", "T.B", "T.C", "T.D", "T.E", "T.F"]);
    expect(parse("package a\nfunc (t *T[K]) C() {}\n").symbols[0]?.id).toBe("sym:r:pkg/a.go#T.C");
  });
});

describe("go const and var specs", () => {
  it("indexes every name of `const a, b = 1, 2` once (the comma is not a name)", () => {
    const names = parse("package a\nconst a, b = 1, 2\n").symbols.map((s) => s.name);
    expect(names).toEqual(["a", "b"]);
  });

  it("indexes grouped var specs and blank identifiers", () => {
    const syms = parse("package a\nvar (\n\tx = 1\n\ty, z = 2, 3\n\t_ = 4\n\t_ = 5\n)\n").symbols;
    expect(syms.map((s) => s.id.split("#")[1])).toEqual(["x", "y", "z", "_", "_~2"]);
    expect(syms.every((s) => s.kind === "const")).toBe(true);
  });

  it("ignores local declarations inside functions", () => {
    const names = parse(
      "package a\nfunc F() {\n\tconst k = 1\n\tvar v = 2\n\ttype t int\n\t_, _ = k, v\n}\n",
    ).symbols.map((s) => s.name);
    expect(names).toEqual(["F"]);
  });
});

describe("go ids", () => {
  it("gives the same function in two build-constrained files two distinct ids", () => {
    const a = parse("package net\nfunc listen() {}\n", "internal/net/listen.go").symbols[0];
    const b = parse("//go:build unix\n\npackage net\nfunc listen() {}\n", "internal/net/listen_unix.go")
      .symbols[0];
    expect(a?.id).toBe("sym:r:internal/net/listen.go#listen");
    expect(b?.id).toBe("sym:r:internal/net/listen_unix.go#listen");
    expect(a?.id).not.toBe(b?.id);
  });

  it("numbers repeated init functions in source order", () => {
    const ids = parse("package a\nfunc init() {}\nfunc init() {}\nfunc init() {}\n").symbols.map((s) => s.id);
    expect(ids).toEqual(["sym:r:pkg/a.go#init", "sym:r:pkg/a.go#init~2", "sym:r:pkg/a.go#init~3"]);
  });
});

describe("go file facts", () => {
  it("reads imports with their path and optional alias", () => {
    const imports = parse(`package a
import "fmt"
import (
	str "example.com/x/text"
	. "example.com/y"
	_ "example.com/z/v2"
)
`).imports;
    expect(imports.map((i) => [i.local, i.specifier])).toEqual([
      ["fmt", "fmt"],
      ["str", "example.com/x/text"],
      [".", "example.com/y"],
      ["_", "example.com/z/v2"],
    ]);
  });

  it("marks a file with the generated header", () => {
    expect(parse("// Code generated by x. DO NOT EDIT.\n\npackage a\n").directives).toEqual(["generated"]);
    expect(parse("package a\n// Code generated by x. DO NOT EDIT. no\n").directives).toBeUndefined();
  });

  it("measures statements and branches of a function body", () => {
    const f = parse(
      "package a\nfunc F(a int) int {\n\tif a > 1 && a < 5 {\n\t\treturn 1\n\t}\n\tx := a\n\treturn x\n}\n",
    ).symbols[0];
    expect(f?.stmtCount).toBe(4);
    expect(f?.complexity).toBe(3);
    expect(f?.signature).toBe("(a int) int");
    expect([f?.startLine, f?.endLine]).toEqual([2, 8]);
  });

  it("reports a syntax error but keeps the declarations around it", () => {
    const p = parse("package a\nfunc Ok() {}\nfunc Bad( {\n");
    expect(p.errors.length).toBeGreaterThan(0);
    expect(p.symbols.map((s) => s.name)).toContain("Ok");
  });

  it("gives UTF-16 offsets for sources with multi-byte characters", () => {
    const src = "package a\n// héllo 😀\nfunc F() {}\n";
    const p = parse(src);
    const r = p.bodies.get(p.symbols[0]?.id as string) as { start: number; end: number };
    expect(src.slice(r.start, r.end)).toBe("func F() {}");
  });
});

describe("go token streams", () => {
  const streamsOf = (src: string, name: string) => {
    const p = parse(src);
    const sym = p.symbols.find((s) => s.name === name);
    return goStreams(src, p.bodies.get(sym?.id as string) as { start: number; end: number }, "a.go");
  };

  it("renames locals and ignores comments, so a renamed copy hashes the same", () => {
    const a = streamsOf("package a\nfunc F(x int) int {\n\t// double\n\ty := x * 2\n\treturn y\n}\n", "F");
    const b = streamsOf("package a\nfunc F(n int) int {\n\tm := n * 2\n\treturn m\n}\n", "F");
    expect(hashStreams(a).exactHash).toBe(hashStreams(b).exactHash);
    expect(a.exact).toContain("$1");
    expect(a.shape).toContain("ID");
  });

  it("separates different literals in exact but not in shape", () => {
    const a = streamsOf('package a\nfunc F() string { return "a" + "b" }\n', "F");
    const b = streamsOf('package a\nfunc F() string { return "c" + "d" }\n', "F");
    expect(hashStreams(a).exactHash).not.toBe(hashStreams(b).exactHash);
    expect(hashStreams(a).shapeHash).toBe(hashStreams(b).shapeHash);
  });

  it("records references to the function's own name for the near tier", () => {
    const s = streamsOf(
      "package a\nfunc Fact(n int) int {\n\tif n < 2 {\n\t\treturn 1\n\t}\n\treturn n * Fact(n-1)\n}\n",
      "Fact",
    );
    expect(s.selfRefs.length).toBe(2); // the declaration name and the recursive call
    const renamed = streamsOf(
      "package a\nfunc Other(n int) int {\n\tif n < 2 {\n\t\treturn 1\n\t}\n\treturn n * Other(n-1)\n}\n",
      "Other",
    );
    expect(hashStreams(s).renamedHash).toBe(hashStreams(renamed).renamedHash);
  });

  it("builds the embedding text without comments and with collapsed whitespace, locals and own name renamed, strings reduced", () => {
    const src =
      'package a\nfunc F(n int) string {\n\t// note\n\tx   := n\n\tif x > 1 {\n\t\treturn F(x - 1) + "ab" + s.name\n\t}\n\treturn `raw`\n}\n';
    const p = parse(src);
    const r = p.bodies.get(p.symbols[0]?.id as string) as { start: number; end: number };
    expect(goEmbeddingText(src, r, "a.go")).toBe(
      'func v1(v2 int) string { v3 := v2 if v3 > 1 { return v1(v3 - 1) + "s" + s.name } return "s" }',
    );
  });

  it("gives a copy under another name, with other local names, the same embedding text", () => {
    const text = (src: string): string => {
      const p = parse(src);
      const r = p.bodies.get(p.symbols[0]?.id as string) as { start: number; end: number };
      return goEmbeddingText(src, r, "a.go");
    };
    expect(
      text(
        "package a\nfunc Sum(xs []int) int {\n\tt := 0\n\tfor _, x := range xs {\n\t\tt += x\n\t}\n\treturn t\n}\n",
      ),
    ).toBe(
      text(
        "package a\nfunc Total(vals []int) int {\n\tacc := 0\n\tfor _, v := range vals {\n\t\tacc += v\n\t}\n\treturn acc\n}\n",
      ),
    );
  });
});

describe("go manifests", () => {
  it("reads the module path and require lines in single and block form", () => {
    const mod = `module example.com/m // comment

go 1.22

require example.com/a v1.0.0
require (
	example.com/b v1.2.3 // indirect
	example.com/c v0.0.0-20240101000000-abcdef
)
replace example.com/a => ../a
`;
    expect(parseModulePath(mod)).toBe("example.com/m");
    expect(parseRequires(mod)).toEqual(["example.com/a", "example.com/b", "example.com/c"]);
  });

  it("reads go.work use directives in single and block form", () => {
    expect(parseGoWorkUses("go 1.22\n\nuse (\n\t.\n\t./tools\n)\nuse ./extra\n")).toEqual([
      ".",
      "tools",
      "extra",
    ]);
  });
});
