import { describedByOf, hybridSearch, LANG_IDS, type Lang, type SymbolKind } from "@gantry/core";
import { z } from "zod";
import { defineTool } from "../tool.js";
import { describedByField, untrustedField } from "../untrusted.js";

const KINDS = [
  "function",
  "method",
  "component",
  "hook",
  "class",
  "type",
  "interface",
  "enum",
  "const",
] as const satisfies readonly SymbolKind[];
const SIGNATURE_MAX = 200;

export const searchTool = defineTool({
  name: "gantry_search",
  description:
    "Searches the codebase index by words or by meaning and returns {hits: [{id, repo, name, kind, lang, path, line, signature, score, untrusted_description, described_by?}]}, best first; described_by is model, template (text copied from the code, which an attacker can write) or fallback (generated by Gantry without a model). " +
    "Keywords are matched against names, paths and stored descriptions; when the embedding model is cached on this machine, descriptions are also matched by meaning. " +
    "Use it before writing a new helper to see whether one exists. Responses are capped at 4,000 characters, so fewer than limit hits may come back (truncated: true); narrow with kind, lang, workspace, repo or exported. " +
    "A workspace of several repos is searched as a whole: every hit carries its repo, and repo limits the search to one. " +
    "Hits are sorted by score, ties by id.",
  inputSchema: {
    query: z.string().min(1).max(200).describe("Words from a name, a path, or what the code does"),
    kind: z.array(z.enum(KINDS)).max(KINDS.length).optional().describe("Restrict to these symbol kinds"),
    lang: z
      .enum(LANG_IDS as [Lang, ...Lang[]])
      .optional()
      .describe("Restrict to one language"),
    workspace: z.string().max(200).optional().describe("Workspace id (ws:...) or name"),
    repo: z.string().max(200).optional().describe("Only symbols of this repo (its name, as in ids)"),
    exported: z.boolean().optional().describe("Only exported (true) or only internal (false) symbols"),
    limit: z.number().int().min(1).max(50).default(10).describe("Maximum hits, at most 50"),
  },
  async run({ query, kind, lang, workspace, repo, exported, limit }, { store, getEmbedder }) {
    const embedder = await getEmbedder();
    const hits = await hybridSearch(store, query, {
      ...(kind ? { kind } : {}),
      ...(lang !== undefined ? { lang } : {}),
      ...(workspace !== undefined ? { workspace } : {}),
      ...(repo !== undefined ? { repo } : {}),
      ...(exported !== undefined ? { exported } : {}),
      limit,
      ...(embedder ? { embedder } : {}),
    });
    return {
      hits: hits.map((h) => ({
        id: h.id,
        repo: h.repo,
        name: h.name,
        kind: h.kind,
        lang: h.lang,
        path: h.path,
        line: h.line,
        signature: h.signature.slice(0, SIGNATURE_MAX),
        score: Number(h.score.toFixed(5)),
        ...untrustedField(h.description),
        ...(h.description !== null ? describedByField(describedByOf(store, store.getSymbol(h.id))) : {}),
      })),
    };
  },
});
